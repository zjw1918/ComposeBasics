package com.lanqi.qiwei.model



/** 一道菜的数据。只描述“是什么”，不管怎么显示。 */
data class Recipe(
    val id: Int,
    val title: String,
    val subtitle: String,
    val category: String,
    val minutes: Int,
    val difficulty: String,
    val rating: Double,
    /** 两人份的用量 */
    val ingredients: List<Ingredient> = emptyList(),
    val steps: List<String> = emptyList(),
    val imageUrl: String = "",
)

/** 一样食材：名字、两人份的用量、单位。 */
data class Ingredient(val name: String, val amount: Double, val unit: String)

val categories = listOf("全部", "家常", "快手", "汤", "硬菜")

private fun i(name: String, amount: Double, unit: String) = Ingredient(name, amount, unit)

