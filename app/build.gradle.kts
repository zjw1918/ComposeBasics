// 签名用的密码放在仓库根目录的 keystore.properties 里（不进 git，见 .gitignore）
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

android {
    namespace = "com.lanqi.qiwei"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "com.lanqi.qiwei"
        minSdk = 24
        targetSdk = 37
        versionCode = 1
        versionName = "1.0"  // 鳍味 1.0

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        create("release") {
            if (!keystoreProperties.isEmpty) {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // 没有 keystore.properties 的人也能编译，只是装不上（没签名）
            if (!keystoreProperties.isEmpty) signingConfig = signingConfigs.getByName("release")
            optimization {
                enable = true
                packageScope = setOf("androidx.**", "kotlin.**", "kotlinx.**")
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
    }
    // 单元测试跑在电脑的 JVM 上，没有真的 Android：Log.d 这类调用直接返回默认值，而不是抛异常
    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

